class SkyPerfectUltimate:
    def __init__(self):
        self.base_url = "https://www.skyperfectv.co.jp"
        self.session = requests.Session()
        self.session.headers.update({
            'User-Agent': 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36'
        })

    def get_deep_info(self, detail_url):
        """进入节目详情页抓取详细介绍和高清海报"""
        try:
            time.sleep(random.uniform(0.1, 0.3))
            res = self.session.get(detail_url, timeout=10)
            if res.status_code != 200: return "", ""
            soup = BeautifulSoup(res.text, 'html.parser')
            
            # 抓取长文本描述
            desc_node = soup.select_one('.p-program-detail__content')
            desc = desc_node.get_text(separator="\n").strip() if desc_node else ""
            
            # 抓取海报
            img_node = soup.select_one('.p-program-detail__figure img')
            icon = ("https:" + img_node['src']) if img_node and img_node.get('src') else ""
            return desc, icon
        except:
            return "", ""

    def fetch_channel(self, ch_num, srv_ref, name, date_str):
        """抓取并修正30小时制时间逻辑"""
        url = f"{self.base_url}/program/schedule/premium/channel:{ch_num}/?date={date_str}"
        progs = []
        try:
            res = self.session.get(url, timeout=15)
            if res.status_code != 200: return []
            soup = BeautifulSoup(res.text, 'html.parser')
            items = soup.select('.p-program-list__item')

            for item in items:
                t_node = item.select_one('.p-program-list__time')
                a_node = item.select_one('.p-program-list__title a')
                if not t_node or not a_node: continue

                def time_fix(t_raw, b_date):
                    h, m = map(int, t_raw.split(':'))
                    dt = datetime.strptime(b_date, "%Y%m%d")
                    if h >= 24: dt += timedelta(days=1); h -= 24
                    return dt.replace(hour=h, minute=m).strftime("%Y%m%d%H%M%S +0900")

                start_raw, end_raw = t_node.text.strip().split('～')
                d_url = self.base_url + a_node['href']
                
                # 抓取深度描述和图片
                full_desc, icon_url = self.get_deep_info(d_url)

                progs.append({
                    'ref': srv_ref,
                    'start': time_fix(start_raw, date_str),
                    'stop': time_fix(end_raw, date_str),
                    'title': a_node.text.strip(),
                    'desc': full_desc,
                    'icon': icon_url
                })
            print(f"✅ {name} 抓取成功")
        except Exception as e:
            print(f"❌ {name} 失败: {e}")
        return progs

    def run(self, days=2):
        all_results = []
        with ThreadPoolExecutor(max_workers=5) as executor:
            tasks = []
            for i in range(days):
                d_str = (datetime.now() + timedelta(days=i)).strftime("%Y%m%d")
                for ch_num, (srv_ref, name) in CHANNELS_MAP.items():
                    tasks.append(executor.submit(self.fetch_channel, ch_num, srv_ref, name, d_str))
            
            for f in as_completed(tasks):
                all_results.extend(f.result())

        # 生成 XMLTV 格式
        root = ET.Element("tv")
        for ch_num, (srv_ref, name) in CHANNELS_MAP.items():
            chan = ET.SubElement(root, "channel", id=srv_ref)
            ET.SubElement(chan, "display-name").text = name

        for p in all_results:
            prog = ET.SubElement(root, "programme", start=p['start'], stop=p['stop'], channel=p['ref'])
            ET.SubElement(prog, "title", lang="ja").text = p['title']
            if p['desc']: ET.SubElement(prog, "desc", lang="ja").text = p['desc']
            if p['icon']: ET.SubElement(prog, "icon", src=p['icon'])

        tree = ET.ElementTree(root)
        ET.indent(tree, space="  ")
        tree.write("epg_ultimate.xml", encoding="utf-8", xml_declaration=True)
        print(f"\n🚀 任务完成！生成的 EPG 已保存至 epg_ultimate.xml")

if __name__ == "__main__":
    SkyPerfectUltimate().run()
